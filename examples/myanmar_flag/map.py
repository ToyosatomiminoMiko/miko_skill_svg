"""国土轮廓部件: 缅甸大陆剪影, 单个闭合多边形.

是什么:
    移植自 myama 的 `miko_wiki_resource/parts/map_outline.py` + `map_points.py`.
    POINTS_SVG 是 myama 从 map.svg 采样出的国土轮廓顶点(单位 = map.svg 用户坐标),
    点列以"轮廓面积质心"为原点(即 myama 的 ANCHOR_SVG), 首点不重复.

    导出 `map_elements()`: 一个 `<polygon>`, 坐标 = 设计单位、原点 = 轮廓面积质心、
    y 向下; 点列先按 MAP_SCALE 放大到设计单位, 再绕原点旋转 MAP_ROTATION_DEG.

为什么:
    - 缩放/旋转绕面积质心做: 这样 MAP_CENTER_OFFSET_X/Y 的含义就是"质心放在旗面哪里",
      位置参数与旋转参数解耦; 旋转不改变质心, 所以处理完点列后原点仍是质心;
    - 采样点写死在本文件里而不是运行时解析 map.svg: map.svg 的可见国土要先做布尔运算/
      栅格化才能得到, 放进生成链路会引入外部大文件与工具依赖; 采样一次(269 点, 误差
      压在一个像素以内)存成数据后, 生成链路就只剩纯几何变换, 输出可复现;
    - 点列本身由 myama 的 map_fit.py 生成(高斯平滑 -> potrace -> Douglas-Peucker,
      南尾一小段用参考旗面的等值线替换), 这里只做复制, 不重新拟合.

元信息: 2026-11-12; POINTS_SVG 原样复制自 myama parts/map_points.py(生成于 2026-10-20),
        采样参数 269 点 / map.svg 画布 1228.352x2003.165.
"""

