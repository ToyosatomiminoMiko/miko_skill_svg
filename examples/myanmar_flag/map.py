def map_elements() -> list[Element]:
    """返回国土轮廓的图元: 一个闭合多边形.

    坐标: 轮廓面积质心 = 原点, 设计单位, y 向下; 白色填充.
    变换顺序与 myama outline_geometry() 一致: 先按 MAP_SCALE 放大, 再绕原点旋转
    MAP_ROTATION_DEG; 质心在旋转/缩放下不动, 所以处理完原点仍是质心.
    """
    scaled = [(x * c.MAP_SCALE, y * c.MAP_SCALE) for x, y in POINTS_SVG]
    points = rotate(scaled, c.MAP_ROTATION_DEG)
    return [Polygon(points, fill=c.EMBLEM_WHITE)]
